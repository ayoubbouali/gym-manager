-- V10 — club charges (electricity, water, internet…). A permanent charge is due every month from its creation month
-- until it is stopped (end_period); a one-off charge concerns one month, its amount may be unknown until it is paid.
-- One payment per charge and month.

CREATE TABLE charges (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label        VARCHAR(120) NOT NULL,
    category     VARCHAR(20) NOT NULL,
    permanent    BOOLEAN NOT NULL,
    period       VARCHAR(7),                  -- one-off: YYYY-MM concerned
    amount       NUMERIC(12, 2) CHECK (amount > 0),  -- one-off: amount when known
    start_period VARCHAR(7),                  -- permanent: first month due
    end_period   VARCHAR(7),                  -- permanent: last month due once stopped
    note         VARCHAR(500) NOT NULL DEFAULT '',
    created_at   TIMESTAMP NOT NULL,
    created_by   VARCHAR(50) NOT NULL,
    CONSTRAINT ck_charges_type CHECK (
        (permanent AND period IS NULL AND amount IS NULL AND start_period IS NOT NULL)
        OR (NOT permanent AND period IS NOT NULL AND start_period IS NULL AND end_period IS NULL))
);

CREATE TABLE charge_payments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    charge_id  BIGINT NOT NULL REFERENCES charges (id),
    period     VARCHAR(7) NOT NULL,           -- YYYY-MM paid
    amount     NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    method     VARCHAR(20) NOT NULL,
    paid_on    DATE NOT NULL,
    note       VARCHAR(500) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL,
    created_by VARCHAR(50) NOT NULL,
    updated_at TIMESTAMP,
    updated_by VARCHAR(50),
    CONSTRAINT uq_charge_payments_charge_period UNIQUE (charge_id, period)
);

