-- V12 — club business (sales of kimonos, clothes, supplements, coaching, private sessions…), the mirror of charges:
-- a permanent item is due every month from its creation month until stopped, a one-off item concerns one month.
-- An item may be linked to a member: its amount is added to the member's price and what is left to collect to their balance.
-- Internal staff (club owners) have no pay mode and never appear in the payroll.

CREATE TABLE businesses (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label           VARCHAR(120) NOT NULL,
    category        VARCHAR(20) NOT NULL,
    permanent       BOOLEAN NOT NULL,
    period          VARCHAR(7),                          -- one-off: YYYY-MM concerned
    amount          NUMERIC(12, 2) CHECK (amount > 0),   -- known amount (monthly for a permanent item)
    start_period    VARCHAR(7),                          -- permanent: first month due
    end_period      VARCHAR(7),                          -- permanent: last month due once stopped
    auto_pay        BOOLEAN NOT NULL DEFAULT FALSE,
    auto_method     VARCHAR(20),
    auto_paid_until VARCHAR(7),
    member_id       BIGINT REFERENCES members (id) ON DELETE SET NULL,
    note            VARCHAR(500) NOT NULL DEFAULT '',
    created_at      TIMESTAMP NOT NULL,
    created_by      VARCHAR(50) NOT NULL,
    CONSTRAINT ck_businesses_type CHECK (
        (permanent AND period IS NULL AND start_period IS NOT NULL
            AND (NOT auto_pay OR (amount IS NOT NULL AND auto_method IS NOT NULL)))
        OR (NOT permanent AND period IS NOT NULL AND start_period IS NULL AND end_period IS NULL AND NOT auto_pay))
);

CREATE TABLE business_payments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT NOT NULL REFERENCES businesses (id),
    period      VARCHAR(7) NOT NULL,                     -- YYYY-MM collected
    amount      NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    method      VARCHAR(20) NOT NULL,
    paid_on     DATE NOT NULL,
    note        VARCHAR(500) NOT NULL DEFAULT '',
    created_at  TIMESTAMP NOT NULL,
    created_by  VARCHAR(50) NOT NULL,
    updated_at  TIMESTAMP,
    updated_by  VARCHAR(50),
    CONSTRAINT uq_business_payments_business_period UNIQUE (business_id, period)
);

-- the new page and its correction right go to the roles that manage the club (access to the settings)
