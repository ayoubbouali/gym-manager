-- V7 — monthly bonus of a staff member, paid together with the salary of that month (one payment per month).
-- A bonus without a payment is only a pending amount: it goes away with the staff member.

CREATE TABLE salary_bonuses (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id   BIGINT NOT NULL REFERENCES staff (id) ON DELETE CASCADE,
    period     VARCHAR(7) NOT NULL,           -- YYYY-MM
    amount     NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
    note       VARCHAR(500) NOT NULL DEFAULT '',
    created_at TIMESTAMP NOT NULL,
    created_by VARCHAR(50) NOT NULL,
    CONSTRAINT uq_salary_bonuses_staff_period UNIQUE (staff_id, period)
);
